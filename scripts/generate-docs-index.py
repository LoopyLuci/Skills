"""Generate the complete per-skill documentation index.

Reads the build index (``dist/skills-index.json``, produced by the ``build``
pipeline stage) and writes ``docs/skills-index.md`` — every skill in the
repository, grouped by category, with its description and a link.

Re-run after ``python -m ci --full`` (or ``python -m ci --only build``):

    python scripts/generate-docs-index.py
"""

from __future__ import annotations

import json
from collections import OrderedDict
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
INDEX = ROOT / "dist" / "skills-index.json"
OUT = ROOT / "docs" / "skills-index.md"

# Ordered: the first category whose keyword matches a skill's tags wins.
CATEGORIES: list[tuple[str, list[str]]] = [
    ("Software Development & Engineering", [
        "backend", "frontend", "api", "docker", "kubernetes", "devops", "ci",
        "git", "python", "javascript", "typescript", "react", "angular", "vue",
        "node", "java", "golang", "go", "rust", "cpp", "c-", "php", "ruby",
        "dotnet", "django", "fastapi", "spring", "express", "flask", "testing",
        "tdd", "architecture", "database", "sql", "postgres", "mysql", "mongo",
        "redis", "elastic", "graphql", "web", "mobile", "android", "ios", "flutter",
        "embedded", "game", "blockchain", "crypto",
    ]),
    ("Cloud & Infrastructure", [
        "aws", "azure", "gcp", "google-cloud", "cloud", "terraform", "ansible",
        "network", "dns", "linux", "windows", "powershell", "serverless",
        "observability", "monitoring", "datadog", "docker", "kubernetes", "oss",
    ]),
    ("Cybersecurity", [
        "security", "pentest", "vulnerability", "threat", "incident", "malware",
        "forensic", "compliance", "authorization", "authentication", "oauth",
        "encryption", "hipaa", "gdpr", "soc", "audit", "appsec",
    ]),
    ("Data Science, AI & Machine Learning", [
        "data", "ai", "ml", "llm", "model", "embedding", "vector", "rag",
        "pytorch", "tensorflow", "pandas", "numpy", "analytics", "statistics",
        "machine-learning", "deep-learning", "nlp", "computer-vision",
    ]),
    ("Business, Product & Management", [
        "business", "marketing", "sales", "finance", "accounting", "product",
        "management", "crm", "email", "legal", "project", "hr", "operations",
        "strategy", "customer", "brand", "pricing", "startup",
    ]),
    ("Science, Research & Healthcare", [
        "biotech", "medic", "health", "physics", "chemistry", "biology", "research",
        "climate", "energy", "agri", "pharma", "clinical", "neuro", "genetic",
        "environment", "space",
    ]),
    ("Engineering & Manufacturing", [
        "aviation", "aerospace", "automotive", "electrical", "mechanical", "civil",
        "chemical", "manufacturing", "electronics", "robotics", "quantum",
        "semiconductor", "energy",
    ]),
    ("Creative, Design & Media", [
        "design", "ui", "ux", "animation", "video", "music", "photo", "writing",
        "creative", "illustration", "typography", "figma", "fashion", "beauty",
        "content",
    ]),
    ("Education & Personal Development", [
        "education", "learning", "teaching", "productivity", "career", "wellness",
        "fitness", "nutrition", "meditation", "language", "skill",
    ]),
    ("Government, Law & Public Policy", [
        "government", "law", "policy", "ethics", "nonprofit", "public",
    ]),
]
OTHER = "General & Other"


def categorize(tags: list[str]) -> str:
    for name, keywords in CATEGORIES:
        for tag in tags:
            low = tag.lower()
            if any(low == kw or low.startswith(kw) for kw in keywords):
                return name
    return OTHER


def load_index() -> list[dict]:
    payload = json.loads(INDEX.read_text(encoding="utf-8"))
    return payload.get("skills", [])


def render(skills: list[dict]) -> str:
    groups: "OrderedDict[str, list[dict]]" = OrderedDict()
    for name, _ in CATEGORIES:
        groups[name] = []
    groups[OTHER] = []

    for entry in skills:
        groups[categorize(entry.get("tags", []))].append(entry)

    lines = [
        "# Skills Index",
        "",
        "_Generated by `scripts/generate-docs-index.py` from `dist/skills-index.json`. "
        "Do not edit by hand._",
        "",
        f"**{len(skills):,} skills** across {len([g for g in groups.values() if g])} "
        f"categories. Every entry links to its `SKILL.md`.",
        "",
        "## Contents",
        "",
    ]
    for name, entries in groups.items():
        if entries:
            anchor = name.lower().replace(" ", "-").replace(",", "").replace("&", "and")
            lines.append(f"- [{name}](#{anchor}) ({len(entries):,})")
    lines.append("")

    for name, entries in groups.items():
        if not entries:
            continue
        lines.append(f"## {name}")
        lines.append("")
        for entry in sorted(entries, key=lambda e: e["name"]):
            desc = (entry.get("description") or "").strip().replace("\n", " ")
            if len(desc) > 160:
                desc = desc[:157] + "..."
            suffix = " · adapted" if entry.get("adapted") else ""
            lines.append(f"- [{entry['name']}](../skills/{entry['name']}/SKILL.md){suffix} — {desc}")
        lines.append("")
    return "\n".join(lines)


def main() -> int:
    if not INDEX.exists():
        print(f"missing {INDEX}; run `python -m ci --only build` first")
        return 1
    skills = load_index()
    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text(render(skills), encoding="utf-8")
    print(f"wrote {OUT.relative_to(ROOT)} ({len(skills):,} skills)")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
